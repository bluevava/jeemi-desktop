func TestBuiltInBrowserValidationAndDisabledPlans(t *testing.T) {
	now := time.Now()
	input := RuleSet{Name: "Browser", SourceType: "inline", Behavior: "classical", DefaultBrowser: true, PayloadYAML: "# generated process\npayload: []\n"}
	normalized, err := normalizeRuleSet(input, now)
	if err != nil || normalized.PayloadYAML != input.PayloadYAML {
		t.Fatal("browser rule cannot retain an empty editable payload", err)
	}
	input.DefaultBrowser = false
	if _, err = normalizeRuleSet(input, now); err == nil {
		t.Fatal("ordinary empty rule set accepted")
	}
	input.DefaultBrowser = true
	input.Behavior = "domain"
	if _, err = normalizeRuleSet(input, now); err == nil {
		t.Fatal("domain browser metadata accepted")
	}
	input.Behavior = "classical"
	input.SourceType = "http"
	input.URL = "https://example.invalid/rules"
	if _, err = normalizeRuleSet(input, now); err == nil {
		t.Fatal("remote browser metadata accepted")
	}
	state := State{StrategyGroups: []StrategyGroup{{ID: "group", RuleSetReferences: []RuleSetReference{{RuleSetID: "rule"}}}}, RuleSets: []RuleSet{{ID: "rule", DefaultBrowser: true}}}
	plan := DefaultPlan()
	plan.StrategyGroupIDs = []string{"group"}
	if !UsesBuiltInBrowser(state, plan) {
		t.Fatal("enabled browser rule not detected")
	}
	plan.RulesDisabled = true
	if UsesBuiltInBrowser(state, plan) {
		t.Fatal("disabled plan requested browser rules")
	}
	plan.RulesDisabled = false
	plan.DisabledStrategyGroupIDs = []string{"group"}
	if UsesBuiltInBrowser(state, plan) {
		t.Fatal("disabled group requested browser rules")
	}
}

func TestAutoGeneratedNameCollisionRejectedOnSave(t *testing.T) {
	store, err := NewStore(StoreOptions{DataDirectory: t.TempDir()})
	if err != nil {
		t.Fatal(err)
	}
	if _, err = store.SaveStrategyGroup(StrategyGroup{Name: "AI", Kind: "selector", Type: "select", AutoSelect: true}); err != nil {
		t.Fatal(err)
	}
	if _, err = store.SaveStrategyGroup(StrategyGroup{Name: "AI Auto", Kind: "selector", Type: "select"}); err == nil || !strings.Contains(err.Error(), "Auto") {
		t.Fatal("generated group collision was accepted", err)
	}
	state, err := store.State()
	if err != nil || len(state.StrategyGroups) != 1 {
		t.Fatal("collision changed resources", err)
	}
	if _, err = materializeSelectors([]string{state.StrategyGroups[0].ID}, map[string]StrategyGroup{state.StrategyGroups[0].ID: state.StrategyGroups[0]}, []proxyRecord{{Name: "AI Auto", Type: "ss"}}); err == nil {
		t.Fatal("node collision accepted")
	}
}

func TestConnectionEntryCanAppendToDefaultBrowserRuleSet(t *testing.T) {
	store, err := NewStore(StoreOptions{DataDirectory: t.TempDir()})
	if err != nil {
		t.Fatal(err)
	}
	state, err := store.SaveRuleSet(RuleSet{Name: "Browser", SourceType: "inline", Behavior: "classical", DefaultBrowser: true, PayloadYAML: "# local browser\npayload: []\n"})
	if err != nil {
		t.Fatal(err)
	}
	state, err = store.SaveRuleSetEntryValidated(RuleSetEntryInput{RuleSetID: state.RuleSets[0].ID, ExpectedRevision: state.Revision, MatchType: "processName", Value: "another-browser.exe"}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if !state.RuleSets[0].DefaultBrowser || !strings.Contains(state.RuleSets[0].PayloadYAML, "# local browser") || len(state.RuleSets[0].Payload) != 1 {
		t.Fatal("quick append lost browser metadata or comments")
	}
}
